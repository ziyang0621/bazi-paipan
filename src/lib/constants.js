export function shiShen(dg,s){
  if(!s||!dg)return '';
  if(s===dg)return '比肩';
  var wD=GAN_WX[dg],wS=GAN_WX[s],same=(!!YANG_GAN[dg])===(!!YANG_GAN[s]);
  if(wD===wS)return same?'比肩':'劫财';
  if(sheng(wD,wS))return same?'食神':'伤官';
  if(sheng(wS,wD))return same?'偏印':'正印';
  if(ke(wD,wS))return same?'偏财':'正财';
  if(ke(wS,wD))return same?'七杀':'正官';
  return '';
}

