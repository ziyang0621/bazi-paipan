export function shenSha(yG,mZ,dG,dZ,pillars){
  /* pillars: [{gan,zhi}] 返回每柱神煞名数组 */
  return pillars.map(function(p){
    var r=[];
    function has(list){return list&&list.indexOf(p.zhi)>=0;}
    if(has(TIANYI[yG])||has(TIANYI[dG]))r.push('天乙贵人');
    if(has(WENCHANG[yG]))r.push('文昌贵人');
    if(has(GUOYIN[yG]))r.push('国印贵人');
    if(has(LUSHEN[dG]))r.push('禄神');
    if(has(TIANCHU[dG]))r.push('天厨贵人');
    if(has(HONGYAN[dG]))r.push('红艳煞');
    if(has(REN[dG]))r.push('飞刃');
    var ju1=sanHeJu(pillars[0].zhi),ju2=sanHeJu(dZ);
    [ju1,ju2].forEach(function(ju){
      if(!ju)return;var t=SANHE_SHA[ju];
      if(t.驿马===p.zhi&&r.indexOf('驿马')<0)r.push('驿马');
      if(t.桃花===p.zhi&&r.indexOf('桃花')<0)r.push('桃花');
      if(t.华盖===p.zhi&&r.indexOf('华盖')<0)r.push('华盖');
      if(t.劫煞===p.zhi&&r.indexOf('劫煞')<0)r.push('劫煞');
      if(t.亡神===p.zhi&&r.indexOf('亡神')<0)r.push('亡神');
    });
    if(GUCHEN[yZ0()]===p.zhi)r.push('孤辰');
    if(GUAXIU[yZ0()]===p.zhi)r.push('寡宿');
    function yZ0(){return pillars[0].zhi;}
    var _td=TIANDE[mZ];
    if(_td){if(GAN_WX[_td]){if(p.gan===_td)r.push('天德贵人');}else if(p.zhi===_td)r.push('天德贵人');}
    if(p.gan===YUEDE[mZ])r.push('月德贵人');
    if(DEXIU[mZ]&&DEXIU[mZ].indexOf(p.gan)>=0)r.push('德秀贵人');
    return r;
  });
}

