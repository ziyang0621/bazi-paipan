/* 出生地选择纯逻辑（原 pm* 函数的 DOM 无关部分） */
export function lngStr(lng){return (lng<0?'西经':'东经')+Math.abs(lng)+'°';}
export function getProvinces(){
  var seen={},out=[];
  PLACES.forEach(function(p){if(p[0]!=='cn')return;if(!seen[p[1]]){seen[p[1]]=1;out.push(p[1]);}});
  return out;
}
export function getProvCount(prov){var n=0;PLACES.forEach(function(p){if(p[0]==='cn'&&p[1]===prov)n++;});return n;}
export function getCities(prov){
  return PLACES.filter(function(p){return p[0]==='cn'&&p[1]===prov;})
    .map(function(p){return {name:p[2],prov:p[1],lng:p[3],std:p[4]};});
}
export function getOverseas(tab){
  return PLACES.filter(function(p){return p[0]===tab;})
    .map(function(p){return {name:p[2],country:p[1],lng:p[3],std:p[4]};});
}
export function searchPlaces(kw,tab){
  return PLACES.filter(function(p){
    if(p[0]!==tab)return false;
    if(kw&&(p[1]+p[2]).indexOf(kw)<0)return false;
    return true;
  }).map(function(p){return {name:p[2],prov:p[1],lng:p[3],std:p[4]};});
}
/* 解析出生地输入：城市名 -> [经度, 标准经度]；纯经度数字 -> [经度, 120]；否则 null（与原 trueSolar 逻辑一致） */
export function resolvePlace(place){
  if(!place)return null;
  if(CITY_LNG[place])return {lng:CITY_LNG[place][0],std:CITY_LNG[place][1],label:place};
  var m=place.match(/^(-?\d+(\.\d+)?)\s*[°度]?$/);
  if(m&&!isNaN(parseFloat(m[1])))return {lng:parseFloat(m[1]),std:120,label:'东经'+parseFloat(m[1])+'°'};
  return null;
}
